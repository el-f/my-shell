def test_render_tool_init_subprocess_gets_sanitized_path(
    tmp_project: Path, monkeypatch, tmp_path: Path
):
    """The env handed to a tool's init subprocess must not contain venv PATH entries,
    so generated configs (which bake the subprocess PATH) stay clean."""
    import sys

    from core.merge import _render_tool_init

    venv = str(tmp_path / ".venv")
    monkeypatch.setattr(sys, "prefix", venv)
    monkeypatch.setattr(sys, "base_prefix", str(tmp_path / "base-py"))
    monkeypatch.setenv("VIRTUAL_ENV", venv)
    monkeypatch.setenv(
        "PATH",
        os.pathsep.join([str(Path(venv) / "Scripts"), str(tmp_path / "tools" / "bin")]),
    )

    seen_env: dict = {}

    def _run_capture(cmd, **kwargs):
        seen_env.update(kwargs.get("env") or {})
        return subprocess.CompletedProcess(args=cmd, returncode=0, stdout="init\n", stderr="")

    with (
        patch("core.merge.is_available", return_value=True),
        patch("core.merge.subprocess.run", side_effect=_run_capture),
        patch(
            "core.mise.shutil.which",
            side_effect=lambda t: "/usr/bin/mise" if t == "mise" else None,
        ),
    ):
        out = _render_tool_init("mise", ["mise", "activate", "nu"], project_dir=tmp_project)

    assert out is not None
    path_key = next(k for k in seen_env if k.upper() == "PATH")
