def test_deploy_reports_alias_delta(tmp_project: Path):
    """Re-deploy after editing aliases.toml reports the added/removed alias names."""
    config_dir = tmp_project / "deploy_delta"
    aliases_toml = tmp_project / "config" / "aliases.toml"

    with patch("core.merge.is_available", return_value=False):
        first = deploy("nushell", config_dir=config_dir, project_dir=tmp_project)
        # First render: no prior file, so every alias reads as added, none removed.
        assert "g" in first.aliases_added
        assert first.aliases_removed == []

        # Add one alias, remove one (drop the whole git group's `glog`).
        text = aliases_toml.read_text(encoding="utf-8")
        text = text.replace('glog = "git log --oneline --graph --decorate"\n', "")
        text += '\n[extra]\nzzt = "echo hi"\n'
        aliases_toml.write_text(text, encoding="utf-8")

        second = deploy("nushell", config_dir=config_dir, project_dir=tmp_project, force=True)

    assert second.aliases_added == ["zzt"]
    assert second.aliases_removed == ["glog"]


