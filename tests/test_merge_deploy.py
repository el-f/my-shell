def test_generate_tool_init_uses_resolved_mise_binary(tmp_path: Path):
    """_generate_tool_init invokes the binary resolved through `mise which`."""
    output_path = tmp_path / "zoxide.nu"
    project_dir = tmp_path / "project"
    project_dir.mkdir()

    def _which(tool):
        if tool == "mise":
            return "/usr/bin/mise"
        return None  # zoxide not directly in PATH

    def _run_dispatch(cmd, **kwargs):
        # resolve_command probes mise for the tool path
        if Path(cmd[0]) == Path("/usr/bin/mise") and cmd[1:] == ["which", "zoxide"]:
            assert kwargs["cwd"] == project_dir
            assert str(project_dir) in kwargs["env"]["MISE_TRUSTED_CONFIG_PATHS"]
            return subprocess.CompletedProcess(
                args=cmd,
                returncode=0,
                stdout="/home/user/.local/share/mise/installs/zoxide/latest/bin/zoxide\n",
                stderr="",
            )
        # _generate_tool_init runs the resolved binary directly
        if Path(cmd[0]) == Path(
            "/home/user/.local/share/mise/installs/zoxide/latest/bin/zoxide"
        ) and cmd[1:] == ["init", "nushell"]:
            assert kwargs["cwd"] == project_dir
            assert str(project_dir) in kwargs["env"]["MISE_TRUSTED_CONFIG_PATHS"]
            return subprocess.CompletedProcess(
                args=cmd, returncode=0, stdout="# zoxide init via mise\n", stderr=""
            )
        raise AssertionError(f"Unexpected subprocess call: {cmd}")

    with (
        patch("core.merge.is_available", return_value=True),
        patch("core.mise.shutil.which", side_effect=_which),
        patch("core.mise.subprocess.run", side_effect=_run_dispatch),
        patch("core.merge.subprocess.run", side_effect=_run_dispatch),
    ):
        result = _generate_tool_init(
            "zoxide",
            ["zoxide", "init", "nushell"],
            output_path,
            project_dir=project_dir,
        )

    assert result is True
    assert output_path.exists()
    assert "zoxide init via mise" in output_path.read_text(encoding="utf-8")


