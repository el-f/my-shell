def _guard_dispatch(tool: str, tool_stdout: str, ide_stdout: str):
    """Build a subprocess.run side-effect: `tool` returns tool_stdout, `nu --ide-check`
    returns ide_stdout, anything else returns empty."""

    def _run(cmd, **kwargs):
        name = _resolved_tool_name(cmd)
        if name == tool:
            return subprocess.CompletedProcess(
                args=cmd, returncode=0, stdout=tool_stdout, stderr=""
            )
        if name == "nu":  # the --ide-check parse pass
            return subprocess.CompletedProcess(args=cmd, returncode=0, stdout=ide_stdout, stderr="")
        return subprocess.CompletedProcess(args=cmd, returncode=0, stdout="", stderr="")

    return _run


