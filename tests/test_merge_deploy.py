def test_deploy_nushell_omp_success(tmp_project: Path):
    """When oh-my-posh is available, _deploy_nushell generates its init file."""
    config_dir = tmp_project / "nu-omp-test"
    config_dir.mkdir()

    def _avail(tool):
        return tool == "oh-my-posh"

    # Include the problematic patterns that oh-my-posh (>= 30) actually emits
    omp_raw = (
        "# omp init output\n"
        "    mut execution_time = -1\n"
        "    # initial `$env.CMD_DURATION_MS` is `0823`\n"
        "    if $env.CMD_DURATION_MS != '0823' {\n"
        "        $execution_time = $env.CMD_DURATION_MS\n"
        "    }\n"
        "    let legacy = match $env.CMD_DURATION_MS { '0823' => -1, _ => 0 }\n"
        "            --save-cache\n"
        '            $"--no-status=($no_status)"\n'
        "    ^$_omp_executable print secondary\n"
        "    $clear = (history | is-empty) or "
        '((history | last 1 | get 0.command) == "clear")\n'
    )

    captured_cmds = []

    def _run_dispatch(cmd, **kwargs):
        captured_cmds.append(list(cmd))
        if _resolved_tool_name(cmd) == "oh-my-posh":
            return subprocess.CompletedProcess(args=cmd, returncode=0, stdout=omp_raw, stderr="")
        return subprocess.CompletedProcess(
            args=cmd, returncode=0, stdout="2025-01-01 12:00:00 +0000\n", stderr=""
        )

    with (
        patch("core.merge.is_available", side_effect=_avail),
        patch("core.merge.subprocess.run", side_effect=_run_dispatch),
        patch(
            "core.mise.shutil.which",
            side_effect=lambda t: "/usr/bin/oh-my-posh" if t == "oh-my-posh" else None,
        ),
    ):
        _deploy_nushell(config_dir, tmp_project)

    assert (config_dir / "oh-my-posh.nu").exists()
    omp_content = (config_dir / "oh-my-posh.nu").read_text(encoding="utf-8")
    assert "omp init output" in omp_content
    # Vendor autoload guard should be prepended
    assert "vendor" in omp_content
    assert "oh-my-posh.nu" in omp_content
    assert "path exists" in omp_content
    assert "rm $_vendor_omp" in omp_content
    # Guard should come BEFORE the init output
    guard_pos = omp_content.index("vendor")
    init_pos = omp_content.index("omp init output")
    assert guard_pos < init_pos, "vendor guard should be prepended before init output"
    # CMD_DURATION_MS should use null-safe accessor
    assert "default 823 | into int" in omp_content
    assert "let _history = (history | last 1)" in omp_content
    assert "$clear = if (($_history | length) == 0)" in omp_content
    assert "$clear = (history | is-empty) or" not in omp_content
    assert 'match ($env.CMD_DURATION_MS? | default "0823") {' in omp_content
    assert "if $env.CMD_DURATION_MS" not in omp_content
    assert "$execution_time = $env.CMD_DURATION_MS" not in omp_content
    assert "--no-status" not in omp_content
    # The --config injection should land after --save-cache
    assert omp_content.count("--config=") >= 2
    # The command should include --print flag
    omp_cmds = [c for c in captured_cmds if _resolved_tool_name(c) == "oh-my-posh"]
    assert any("--print" in c for c in omp_cmds), "oh-my-posh init should use --print"
    config_content = (config_dir / "config.nu").read_text(encoding="utf-8")
    assert "LAYER 1" in config_content
    assert "LAYER 2" in config_content
    assert "LAYER 3" in config_content
    assert "$env.MY_SHELL_VERSION = '2025-01-01 12:00:00 +0000'" in config_content


