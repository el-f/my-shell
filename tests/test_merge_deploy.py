def test_xonsh_runtime_check_reports_a_command_that_did_not_register(tmp_path: Path):
    """ "command not found: sysinfo" with a green doctor was the whole failure."""
    from core.doctor import _check_xonsh_runtime

    rc = tmp_path / ".xonshrc"
    rc.write_text("# rc\n", encoding="utf-8")
    proc = subprocess.CompletedProcess(
        args=[],
        returncode=0,
        stdout="MY_SHELL_XONSH_OK\nMY_SHELL_MISSING:sysinfo,commands\n",
        stderr="",
    )
    with (
        patch("core.benchmark._shell_binary", return_value="xonsh"),
        patch("core.doctor.subprocess.run", return_value=proc),
    ):
        result = _check_xonsh_runtime(rc)

    assert result.status == "fail"
    assert "sysinfo" in result.message


def test_xonsh_runtime_check_passes_when_every_command_registered(tmp_path: Path):
    from core.doctor import _check_xonsh_runtime

    rc = tmp_path / ".xonshrc"
    rc.write_text("# rc\n", encoding="utf-8")
    proc = subprocess.CompletedProcess(
        args=[], returncode=0, stdout="MY_SHELL_XONSH_OK\nMY_SHELL_MISSING:\n", stderr=""
    )
    with (
        patch("core.benchmark._shell_binary", return_value="xonsh"),
        patch("core.doctor.subprocess.run", return_value=proc),
    ):
        assert _check_xonsh_runtime(rc).status == "pass"


def test_generated_xonshrc_warns_when_a_command_module_fails_to_import(tmp_project: Path):
    """A silent `except ImportError: pass` leaves the user with a bare shell and no reason."""
    from core.merge import generate_xonsh_config

    content = generate_xonsh_config(config_dir=tmp_project / "xonsh", project_dir=tmp_project)

    assert "except ImportError" in content
    assert content.count("except ImportError:\n    pass") == 0
    assert "my-shell: commands unavailable" in content


def test_xonsh_runtime_check_warns_when_the_rc_was_never_deployed(tmp_path: Path):
    """Enabled + installed + no rc is the bare-shell failure, not a neutral note."""
    from core.doctor import _check_xonsh_runtime

    with patch("core.benchmark._shell_binary", return_value="xonsh"):
        result = _check_xonsh_runtime(tmp_path / "missing.xonshrc")

    assert result.status == "warn"
    assert result.fix and "setup --shell xonsh" in result.fix
