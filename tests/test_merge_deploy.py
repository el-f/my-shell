def test_deploy_nushell_omp_mise_installs_path_rewritten_to_shim(tmp_project: Path, monkeypatch):
    """oh-my-posh init bakes the exe path it was invoked as. A mise installs
    path contains the version dir, so every omp upgrade kills the prompt until
    a redeploy. The shim path never moves -- the deploy rewrites to it."""
    config_dir = tmp_project / "nu-omp-shim"
    config_dir.mkdir()
    shims = tmp_project / "mise-data" / "shims"
    shims.mkdir(parents=True)
    (shims / "oh-my-posh.exe").touch()
    monkeypatch.setenv("MISE_DATA_DIR", str(tmp_project / "mise-data"))

    def _avail(tool):
        return tool == "oh-my-posh"

    def _run_dispatch(cmd, **kwargs):
        if _resolved_tool_name(cmd) == "oh-my-posh":
            return subprocess.CompletedProcess(
                args=cmd,
                returncode=0,
                stdout=(
                    'let _omp_executable: string = (echo "C:/u/mise/installs/'
                    'aqua-jan-de-dobbeleer-oh-my-posh/30.2.0/oh-my-posh.EXE")\n'
                ),
                stderr="",
            )
        return subprocess.CompletedProcess(
            args=cmd, returncode=0, stdout="2025-01-01 12:00:00 +0000\n", stderr=""
        )

    with (
        patch("core.merge.is_available", side_effect=_avail),
        patch("core.merge.subprocess.run", side_effect=_run_dispatch),
        patch("core.mise.shutil.which", return_value=None),
    ):
        _deploy_nushell(config_dir, tmp_project)

    content = (config_dir / "oh-my-posh.nu").read_text(encoding="utf-8")
    assert "/installs/" not in content
    assert (shims / "oh-my-posh.exe").as_posix() in content


