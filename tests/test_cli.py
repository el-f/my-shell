def test_cli_full_roundtrip(tmp_project: Path, tmp_path: Path):
    """Complete user workflow: deploy -> user edits user-custom -> redeploy preserves it."""
    config_dir = tmp_path / "nu_cfg"
    fake_home = tmp_path / "home"
    fake_home.mkdir()

    def _do_setup():
        with ExitStack() as stack:
            _apply_patches(stack, tmp_project, fake_home)
            stack.enter_context(patch("core.merge.get_config_dir", return_value=config_dir))
            stack.enter_context(patch("core.config.get_config_dir", return_value=config_dir))
            return runner.invoke(app, ["setup", "--shell", "nushell"])

    result = _do_setup()
    assert result.exit_code == 0

    config_nu = config_dir / "config.nu"
    assert config_nu.exists()
    assert "Generated by my-shell" in config_nu.read_text(encoding="utf-8")

    user_custom = config_dir / "user-custom.nu"
    user_custom.write_text("# I customized this myself\n", encoding="utf-8")

    result = _do_setup()
    assert result.exit_code == 0
    assert "Generated by my-shell" in config_nu.read_text(encoding="utf-8")

    assert user_custom.read_text(encoding="utf-8") == "# I customized this myself\n"


