def test_cli_deploy_preserves_user_custom(tmp_project: Path, tmp_path: Path):
    """Deploying twice does NOT overwrite user-custom files."""
    config_dir = tmp_path / "nu_cfg"
    fake_home = tmp_path / "home"
    fake_home.mkdir()

    def _do_deploy():
        with ExitStack() as stack:
            _apply_patches(stack, tmp_project, fake_home)
            stack.enter_context(patch("core.merge.get_config_dir", return_value=config_dir))
            stack.enter_context(patch("core.config.get_config_dir", return_value=config_dir))
            return runner.invoke(app, ["deploy", "--shell", "nushell"])

    result = _do_deploy()
    assert result.exit_code == 0
    user_custom = config_dir / "user-custom.nu"
    assert user_custom.exists()

    user_custom.write_text("# my personal config\n", encoding="utf-8")

    result = _do_deploy()
    assert result.exit_code == 0
    assert user_custom.read_text(encoding="utf-8") == "# my personal config\n"


